// Package bodyui adapts a verified, short-lived web admin delegation to the
// existing body tools. Minecraft names and OP status are never web identities.
package bodyui

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
	"sync"
	"time"
	"unicode/utf8"

	"mineagent/internal/agent"
	"mineagent/internal/body"
	"mineagent/internal/protocol"
	"mineagent/internal/session"
	"mineagent/internal/storage"
	"mineagent/internal/tools"
)

const RequestType = "body.ui.request"
const ResponseType = "body.ui.response"

type Request struct {
	ID         string `json:"requestId"`
	UUID       string `json:"uuid"`
	Session    string `json:"session"`
	Player     string `json:"player"`
	Allowed    bool   `json:"allowed"`
	Seq        uint64 `json:"seq"`
	Action     string `json:"action"`
	Text       string `json:"text,omitempty"`
	ApprovalID string `json:"approvalId,omitempty"`
}

type binding struct {
	uuid, nonce, player, code string
	game                      bool
	codeUntil, until          time.Time
	user, authSession         int64
	admin                     string
	seq                       uint64
	generation                uint64
	allowed                   bool
	cancel                    context.CancelFunc
	runID                     string
	lastPair                  time.Time
	messages                  []string
}

type Bridge struct {
	mu        sync.Mutex
	core      *body.Service
	store     *storage.Store
	hub       *session.Hub
	ag        *agent.Agent
	steps     int
	portalURL string
	peer      tools.Sender
	bindings  map[string]*binding
}

func New(core *body.Service, store *storage.Store, hub *session.Hub, ag *agent.Agent, steps int, portalURL string) *Bridge {
	return &Bridge{core: core, store: store, hub: hub, ag: ag, steps: steps, portalURL: strings.TrimSuffix(portalURL, "/"), bindings: map[string]*binding{}}
}

func (b *Bridge) Attach(peer tools.Sender) {
	b.mu.Lock()
	defer b.mu.Unlock()
	for _, v := range b.bindings {
		b.revokeLocked(v)
	}
	b.bindings = map[string]*binding{}
	b.peer = peer
}

func (b *Bridge) Detach(peer tools.Sender) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.peer != peer {
		return
	}
	for _, v := range b.bindings {
		b.revokeLocked(v)
	}
	b.bindings = map[string]*binding{}
	b.peer = nil
}

func (b *Bridge) revokeLocked(v *binding) {
	v.generation++
	v.code = ""
	v.user = 0
	v.authSession = 0
	v.until = time.Time{}
	v.game = false
	v.messages = nil
	if v.cancel != nil {
		v.cancel()
		v.cancel = nil
		// Cancel queued work and latch the existing body's pause independently of its action lock.
		go func() {
			ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
			defer cancel()
			_, _ = b.core.Control(ctx, "stop", nil)
		}()
	}
	v.runID = ""
}

func validID(s string) bool {
	if len(s) != 36 && len(s) != 32 {
		return false
	}
	for _, c := range s {
		if !(c >= 'a' && c <= 'f' || c >= '0' && c <= '9' || c == '-') {
			return false
		}
	}
	return true
}

// Handle is called only for the authenticated, currently attached Paper peer.
// The nonce is generated by the server plugin per player connection, never supplied by a game client.
func (b *Bridge) Handle(ctx context.Context, peer tools.Sender, env *protocol.Envelope) {
	var r Request
	if len(env.Data) > 4096 || json.Unmarshal(env.Data, &r) != nil || !validID(r.UUID) || !validID(r.Session) || !validID(r.ID) || len(r.Player) > 40 || r.Seq == 0 {
		return
	}
	b.mu.Lock()
	if b.peer != peer {
		b.mu.Unlock()
		return
	}
	v := b.bindings[r.UUID]
	if v == nil || v.nonce != r.Session {
		if v != nil {
			b.revokeLocked(v)
		}
		if len(b.bindings) >= 256 && v == nil {
			b.mu.Unlock()
			b.respond(peer, r, nil, "rate_limited")
			return
		}
		v = &binding{uuid: r.UUID, nonce: r.Session, player: r.Player}
		b.bindings[r.UUID] = v
	}
	if r.Seq <= v.seq {
		b.mu.Unlock()
		b.respond(peer, r, nil, "stale_request")
		return
	}
	v.seq = r.Seq
	v.allowed = r.Allowed
	if v.game && r.Allowed {
		v.until = time.Now().Add(30 * time.Minute)
	}
	if !r.Allowed {
		b.revokeLocked(v)
	} else if b.core.DirectControl() {
		v.game = true
		v.user = 0
		v.authSession = 0
		v.admin = v.player
		v.until = time.Now().Add(30 * time.Minute)
	}
	if r.Action == "leave" {
		b.revokeLocked(v)
		delete(b.bindings, r.UUID)
		b.mu.Unlock()
		return
	}
	b.mu.Unlock()
	// Controls and model submission must never block the Paper WS reader.
	go func() {
		workCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		err := b.perform(workCtx, peer, v, r)
		b.respond(peer, r, b.view(workCtx, peer, v), body.ErrorCode(err))
	}()
}

func (b *Bridge) valid(ctx context.Context, peer tools.Sender, v *binding, expected ...uint64) bool {
	b.mu.Lock()
	if v.game {
		valid := b.peer == peer && b.bindings[v.uuid] == v && v.allowed && time.Now().Before(v.until) && (len(expected) == 0 || v.generation == expected[0])
		player, uuid := v.player, v.uuid
		b.mu.Unlock()
		if !valid {
			return false
		}
		return b.core.Check(ctx, b.core.GamePrincipal(player, uuid), true) == nil
	}
	valid := b.peer == peer && b.bindings[v.uuid] == v && v.allowed && v.user > 0 && time.Now().Before(v.until) && (len(expected) == 0 || v.generation == expected[0])
	user, sid, name := v.user, v.authSession, v.admin
	generation := v.generation
	b.mu.Unlock()
	if !valid {
		return false
	}
	p := b.core.Principal(user, sid, name)
	if b.core.Check(ctx, p, true) != nil {
		return false
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.peer == peer && b.bindings[v.uuid] == v && v.allowed && v.user == user && v.authSession == sid && v.generation == generation && time.Now().Before(v.until)
}

func (b *Bridge) principal(ctx context.Context, peer tools.Sender, v *binding) (*body.Principal, error) {
	if !b.valid(ctx, peer, v) {
		return nil, errors.New("link_required")
	}
	b.mu.Lock()
	game, player, uuid, user, sid, name, until := v.game, v.player, v.uuid, v.user, v.authSession, v.admin, v.until
	generation := v.generation
	b.mu.Unlock()
	var p *body.Principal
	if game {
		p = b.core.GamePrincipal(player, uuid)
		// In-game direct control is still a bounded task; a stuck model must not
		// hold the body forever. Thirty minutes is enough for normal UI tasks.
		if p.Deadline.IsZero() {
			p.Deadline = time.Now().Add(30 * time.Minute)
		}
	} else {
		p = b.core.Principal(user, sid, name)
		if p.Deadline.IsZero() || until.Before(p.Deadline) {
			p.Deadline = until
		}
	}
	p.Valid = func(ctx context.Context) bool { return b.valid(ctx, peer, v, generation) }
	return p, nil
}

func (b *Bridge) perform(ctx context.Context, peer tools.Sender, v *binding, r Request) error {
	if r.Action == "status" {
		return nil
	}
	if r.Action == "unlink" {
		b.mu.Lock()
		b.revokeLocked(v)
		b.mu.Unlock()
		return nil
	}
	if !b.core.Enabled() {
		return errors.New("body_disabled")
	}
	if r.Action == "pair" {
		b.mu.Lock()
		defer b.mu.Unlock()
		if v.game {
			return nil
		}
		if b.peer != peer || b.bindings[v.uuid] != v || !v.allowed {
			return errors.New("permission_denied")
		}
		if v.code != "" && time.Now().Before(v.codeUntil) {
			return nil
		}
		if time.Since(v.lastPair) < 5*time.Second {
			return errors.New("rate_limited")
		}
		v.lastPair = time.Now()
		v.code = body.ID()
		v.codeUntil = time.Now().Add(2 * time.Minute)
		return nil
	}
	p, err := b.principal(ctx, peer, v)
	if err != nil {
		return err
	}
	switch r.Action {
	case "stop", "pause", "resume", "disconnect":
		var cancelRun context.CancelFunc
		if r.Action == "stop" || r.Action == "disconnect" {
			b.mu.Lock()
			cancelRun = v.cancel
			b.mu.Unlock()
		}
		_, err = b.core.Control(ctx, r.Action, p)
		// Latch the control epoch before canceling the model run, so its canceled
		// tool cannot race this explicit stop with another internal stop request.
		if cancelRun != nil {
			cancelRun()
		}
		return err
	case "approve", "deny":
		if !b.core.Decide(ctx, p, r.ApprovalID, r.Action == "approve") {
			return errors.New("stale_approval")
		}
		return nil
	case "task":
		return b.submit(ctx, peer, v, p, r.Text)
	default:
		return errors.New("invalid_action")
	}
}

func (b *Bridge) view(ctx context.Context, peer tools.Sender, v *binding) map[string]any {
	linked := b.valid(ctx, peer, v)
	profile := b.core.Profile()
	summary := map[string]any{}
	for _, key := range []string{"id", "name", "displayName", "status", "activity", "updatedAt", "stale"} {
		summary[key] = profile[key]
	}
	out := map[string]any{"enabled": b.core.Enabled(), "profile": summary, "linked": linked, "portalURL": b.portalURL}
	b.mu.Lock()
	if b.peer != peer || b.bindings[v.uuid] != v {
		b.mu.Unlock()
		return out
	}
	out["direct"] = v.game
	out["canLink"] = v.allowed && !v.game
	if v.allowed && !v.game && time.Now().Before(v.codeUntil) {
		out["pairCode"] = v.code
		out["pairExpiresAt"] = v.codeUntil.UnixMilli()
	}
	if linked {
		out["operator"] = v.admin
		if !v.game {
			out["expiresAt"] = v.until.UnixMilli()
		}
		out["running"] = v.cancel != nil
		out["messages"] = append([]string{}, v.messages...)
	}
	b.mu.Unlock()
	if linked {
		out["snapshot"] = b.core.Snapshot()
		out["approvals"] = b.core.Pending()
	}
	return out
}

func (b *Bridge) respond(peer tools.Sender, r Request, data map[string]any, code string) {
	b.mu.Lock()
	current := b.peer == peer && b.bindings[r.UUID] != nil && b.bindings[r.UUID].nonce == r.Session
	b.mu.Unlock()
	if !current {
		return
	}
	_ = peer.SendProtocol(ResponseType, map[string]any{"requestId": r.ID, "uuid": r.UUID, "session": r.Session, "data": data, "error": code})
}

// Chat accepts only the nonce of an existing verified game delegation. A name,
// UUID, OP bit or stale nonce alone can never select the full body tool set.
func (b *Bridge) Chat(ctx context.Context, peer tools.Sender, chat protocol.ChatMessage, query string) bool {
	b.mu.Lock()
	v := b.bindings[chat.UUID]
	// Public in-game chat must never be routed into a direct body task; the
	// body task panel is the only user of this path.
	matched := v != nil && !v.game && chat.Session != "" && v.nonce == chat.Session && v.player == chat.Player && b.peer == peer
	b.mu.Unlock()
	if !matched {
		return false
	}
	p, err := b.principal(ctx, peer, v)
	if err != nil {
		return false
	}
	if err = b.submit(ctx, peer, v, p, query, true); err != nil {
		_ = peer.SendProtocol(protocol.TypeAgentMessage, protocol.AgentMessage{Target: chat.Player, Text: "身体任务暂不可用：" + body.ErrorCode(err)})
	}
	return true
}

func (b *Bridge) submit(ctx context.Context, peer tools.Sender, v *binding, p *body.Principal, text string, chatReply ...bool) error {
	text = strings.TrimSpace(text)
	if text == "" || utf8.RuneCountInString(text) > 512 || strings.ContainsAny(text, "\r\n\x00") {
		return errors.New("invalid_task")
	}
	if b.ag == nil || b.hub == nil {
		return errors.New("agent_unavailable")
	}
	b.mu.Lock()
	if b.peer != peer || b.bindings[v.uuid] != v || v.user != p.UserID || v.authSession != p.AuthSessionID {
		b.mu.Unlock()
		return errors.New("link_required")
	}
	if v.cancel != nil {
		b.mu.Unlock()
		return errors.New("busy")
	}
	runCtx, cancel := context.WithDeadline(context.Background(), p.Deadline)
	runID := body.ID()
	v.cancel = cancel
	v.runID = runID
	uuid, nonce, admin, generation := v.uuid, v.nonce, v.admin, v.generation
	b.mu.Unlock()
	done := func() {
		cancel()
		b.mu.Lock()
		if v.runID == runID {
			v.cancel = nil
			v.runID = ""
		}
		b.mu.Unlock()
	}
	key := fmt.Sprintf("bodyui:%d:%s", p.UserID, nonce)
	player := "web:" + admin
	if p.Game {
		key = fmt.Sprintf("bodyui:game:%s:%s", p.GameUUID, nonce)
		player = "mc:" + v.player
	}
	sess, err := b.hub.Session(ctx, key)
	if err != nil {
		done()
		return errors.New("storage_unavailable")
	}
	sess.Register(&replyChannel{b: b, peer: peer, v: v, generation: generation, chat: len(chatReply) > 0 && chatReply[0]})
	msg, err := sess.Ingest(ctx, storage.Message{Channel: "bodyui", AuthorKind: "player", AuthorID: uuid, AuthorName: admin, Text: text, Target: nonce})
	if err != nil {
		done()
		return errors.New("storage_unavailable")
	}
	instruction := body.Instruction + "\n仅使用身体工具执行当前游戏管理员明确提出的任务，不能调用其他通道或修改服务器配置。"
	if len(chatReply) > 0 && chatReply[0] {
		instruction += "\n这是MC私聊回复：最多80字两行，只答当前问题。"
	}
	ok := b.ag.Submit(agent.Request{Context: runCtx, Done: done, Session: sess, SessionKey: key, Player: player, RequesterID: uuid, Query: text, TriggerMessageID: msg.ID, ReplyTarget: nonce, BodyPrincipal: p, Tools: b.core.Tools(), MaxIterations: b.steps, SystemInstruction: instruction})
	if !ok {
		done()
		return errors.New("agent_unavailable")
	}
	b.record(peer, v, "任务："+text, generation)
	return nil
}

func (b *Bridge) record(peer tools.Sender, v *binding, text string, generation uint64) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.peer != peer || b.bindings[v.uuid] != v || v.generation != generation {
		return
	}
	if len([]rune(text)) > 1600 {
		text = string([]rune(text)[:1600]) + "…"
	}
	v.messages = append(v.messages, text)
	if len(v.messages) > 12 {
		v.messages = v.messages[len(v.messages)-12:]
	}
}

type replyChannel struct {
	b          *Bridge
	peer       tools.Sender
	v          *binding
	generation uint64
	chat       bool
}

func (c *replyChannel) Name() string { return "bodyui" }
func (c *replyChannel) Send(ctx context.Context, msg storage.Message) error {
	if !c.b.valid(ctx, c.peer, c.v, c.generation) {
		return errors.New("controller_expired")
	}
	c.b.record(c.peer, c.v, msg.Text, c.generation)
	if c.chat {
		return c.peer.SendProtocol(protocol.TypeAgentMessage, protocol.AgentMessage{Text: msg.Text, Target: c.v.player})
	}
	return nil
}

func (b *Bridge) Run(ctx context.Context) {
	t := time.NewTicker(time.Second)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			b.mu.Lock()
			for _, v := range b.bindings {
				b.revokeLocked(v)
			}
			b.mu.Unlock()
			return
		case <-t.C:
			b.mu.Lock()
			peer := b.peer
			var list []*binding
			for _, v := range b.bindings {
				if v.user > 0 {
					list = append(list, v)
				}
			}
			b.mu.Unlock()
			for _, v := range list {
				if !b.valid(ctx, peer, v) {
					b.mu.Lock()
					b.revokeLocked(v)
					b.mu.Unlock()
				}
			}
		}
	}
}
